// scripts/vetting-data.mjs - Writes the two lists the API's form checks read (apps/api/src/vetting/):
// every US populated place by state, from GeoNames (CC BY 4.0, credited in NOTICE), and the throwaway
// mailbox domains from the community-kept disposable-email-domains list (CC0). Both are packed as gzip,
// then base64, in a TypeScript module, so the Lambda bundle and the tests read them with no file loader.
// Run it to refresh: node scripts/vetting-data.mjs [path/to/US.txt]. Without a path it downloads
// GeoNames' US.zip (about 70 MB) to a temporary folder and unzips it there.


import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { gzipSync } from "node:zlib";


const out = new URL("../apps/api/src/vetting/", import.meta.url);
const today = new Date().toISOString().slice(0, 10);


// GeoNames: the US file, or one given on the command line
let usTxt = process.argv[2];
if (!usTxt) {
  const dir = mkdtempSync(join(tmpdir(), "geonames-"));
  const zip = join(dir, "US.zip");
  writeFileSync(zip, Buffer.from(await (await fetch("https://download.geonames.org/export/dump/US.zip")).arrayBuffer()));
  execFileSync("unzip", ["-o", "-q", zip, "US.txt", "-d", dir]);
  usTxt = join(dir, "US.txt");
}

// Populated places (feature class P), less the abandoned, historical, and destroyed ones. Columns:
// 1 name, 2 ASCII name, 6 class, 7 code, 10 state. Both spellings are kept, so "Cañon City" and
// "Canon City" both match
const skip = new Set(["PPLQ", "PPLH", "PPLW"]);
const byState = {};
for (const line of readFileSync(usTxt, "utf8").split("\n")) {
  const f = line.split("\t");
  if (f[6] !== "P" || skip.has(f[7]) || !f[10]) continue;
  const set = (byState[f[10]] ??= new Set());
  set.add(f[1]);
  if (f[2] && f[2] !== f[1]) set.add(f[2]);
}
const places = Object.fromEntries(Object.entries(byState).sort().map(([st, set]) => [st, [...set].sort().join("\n")]));
const placesPacked = gzipSync(JSON.stringify(places), { level: 9 }).toString("base64");
const count = Object.values(byState).reduce((n, s) => n + s.size, 0);
writeFileSync(new URL("places-data.ts", out), `// apps/api/src/vetting/places-data.ts - Generated by scripts/vetting-data.mjs on ${today}; don't edit.\n// ${count} US populated place names by state, from GeoNames (geonames.org, CC BY 4.0), as gzipped JSON in base64.\nexport const PLACES_GZ_B64 = "${placesPacked}";\n`);

// Throwaway mailbox domains, one a line
const list = await (await fetch("https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf")).text();
const domains = list.split("\n").map((d) => d.trim().toLowerCase()).filter((d) => d && !d.startsWith("#")).sort();
const domainsPacked = gzipSync(domains.join("\n"), { level: 9 }).toString("base64");
writeFileSync(new URL("disposable-data.ts", out), `// apps/api/src/vetting/disposable-data.ts - Generated by scripts/vetting-data.mjs on ${today}; don't edit.\n// ${domains.length} throwaway mailbox domains from github.com/disposable-email-domains/disposable-email-domains (CC0), gzipped, in base64.\nexport const DISPOSABLE_GZ_B64 = "${domainsPacked}";\n`);

console.log(`places: ${count} names in ${Object.keys(places).length} states (${Math.round(placesPacked.length / 1024)} KB); disposable: ${domains.length} domains (${Math.round(domainsPacked.length / 1024)} KB)`);
